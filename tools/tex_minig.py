def minig4():
    lay = Layout("MINIG4")
    # small bin labels (51x17 each, dark text on a light label)
    data, p, im = load("MINIG4", "juice03")
    # the original grape rect (71,77) points past the texture edge; its label really sits at (0,87)
    im.paste((0, 0, 0, 0), (0, 87, 52, 104))
    i, l = lay.find(r"^\s*grape,\s*juice03.tm2")
    lay.subs.append(f"{i}	<SUB>	uv:71:77:51:17	uv:0:87:51:17")
    for key, name in FRUITS:
        i, l = lay.find(rf"^\s*{key},\s*juice03.tm2")
        x, y, w, h = map(int, re.search(r"uv:(\d+):(\d+):(\d+):(\d+)", l).groups())
        if key == "grape":
            x, y = 0, 87
        put(im, (x, y, w, h), name, dict(BROWN, max=14))
    save("MINIG4", "juice03", data, p, im)

    # order message: "<fruit> & <fruit> Juice" / "Make it， please!" -- re-packed texture
    data, p, im = load("MINIG4", "juice04")
    play = im.crop((1, 146, 116, 181))
    im = Image.new("RGBA", im.size, (0, 0, 0, 0))
    im.alpha_composite(play, (1, 146))
    st = dict(GOLD_N, max=21)
    items = [(k, n) for k, n in FRUITS] + [("point", "&"), ("juice", "Juice")]
    x, y = 0, 0
    for key, text in items:
        spr, size = sprite(text, 28, st, 232)
        w = spr.width + (6 if key == "point" else 4)
        if x + w > 232:
            x, y = 0, y + 28
        im.alpha_composite(spr, (x + (w - spr.width) // 2, y))
        i, l = lay.find(rf"^\s*{key},\s*juice04.tm2")
        old = re.search(r"uv:\d+:\d+:\d+:\d+", l).group(0)
        lay.subs.append(f"{i}\t<SUB>\t{old}\tuv:{x}:{y}:{w}:28")
        x += w
    y += 28
    spr, size = sprite("Make it， please!".replace("，", ","), 28, st, 232)
    im.alpha_composite(spr, (0, y))
    i, l = lay.find(r"^\s*make,\s*juice04.tm2")
    old = re.search(r"uv:\d+:\d+:\d+:\d+", l).group(0)
    lay.subs.append(f"{i}\t<SUB>\t{old}\tuv:0:{y}:{spr.width}:28")
    assert y + 28 <= 146, "juice04 text overlaps PLAY!"
    save("MINIG4", "juice04", data, p, im)
    lay.write()


