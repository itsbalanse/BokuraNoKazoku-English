"""English textures for the minigames (MINIG/*.XAP) plus the matching layout.txt rect edits.

Writes build/mod/MINIG/<X>.XAP/<tex>.tm2 and tl/txt/MINIG/<X>.XAP/layout.txt.tsv
(the layout tsv files are regenerated here; MINIG5's hand-written text entries are kept
in a separate section that this script preserves).
"""
import os, re, sys
from PIL import Image

sys.path.insert(0, os.path.dirname(__file__))
import tm2
from tex_tl import render, W, OUT, PREVIEW

SRC = os.path.join(W, "extracted", "DATA", "MINIG")
TL = os.path.join(W, "tl", "txt", "MINIG")

GOLD = dict(font="arialbd.ttf", top=(232, 214, 140), bot=(190, 160, 80), outline=(16, 16, 16), ow=2)
GOLD_N = dict(GOLD, font="ARIALNB.TTF")
BROWN = dict(font="ARIALNB.TTF", top=(54, 40, 20), bot=(42, 26, 10), outline=None)


def load(xap, name):
    data = open(os.path.join(SRC, xap + ".XAP", name + ".tm2"), "rb").read()
    hdr, pics = tm2.parse(data)
    return data, pics[0], tm2.to_image(pics[0])


def save(xap, name, data, p, im):
    tm2.from_image(p, im)
    new = tm2.rebuild(data, [p])
    dst = os.path.join(OUT, "MINIG", xap + ".XAP", name + ".tm2")
    os.makedirs(os.path.dirname(dst), exist_ok=True)
    open(dst, "wb").write(new)
    os.makedirs(PREVIEW, exist_ok=True)
    tm2.to_image(tm2.parse(new)[1][0]).save(os.path.join(PREVIEW, f"{xap}_{name}.png"))


def sprite(text, h, st, maxw=256):
    """Render text into a tight sprite of height h (width = ink width + outline)."""
    layer, size = render((0, 0, maxw, h), text, st)
    bb = layer.getbbox()
    return layer.crop((bb[0], 0, bb[2], h)), size


def put(im, box, text, st):
    x, y, w, h = box
    im.paste((0, 0, 0, 0), (x, y, x + w, y + h))
    layer, size = render(box, text, st)
    im.alpha_composite(layer, (x, y))
    return size


class Layout:
    """Collect <SUB> edits for one layout.txt."""
    def __init__(self, xap):
        self.xap = xap
        self.lines = open(os.path.join(SRC, xap + ".XAP", "layout.txt"), "rb").read().decode("cp932").split("\r\n")
        self.subs = []

    def find(self, pattern):
        for i, l in enumerate(self.lines, 1):
            if re.search(pattern, l):
                return i, l
        raise SystemExit(f"{self.xap}: no line matches {pattern}")

    def sub(self, pattern, old, new):
        i, l = self.find(pattern)
        assert old in l, (old, l)
        self.subs.append(f"{i}\t<SUB>\t{old}\t{new}")

    def write(self):
        path = os.path.join(TL, self.xap + ".XAP", "layout.txt.tsv")
        keep = []
        if os.path.exists(path):
            txt = open(path, encoding="utf-8").read().split("// --- generated by tex_minig.py ---")[0]
            keep = [l for l in txt.splitlines() if l.strip()]
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w", encoding="utf-8") as f:
            f.write("\n".join(keep + ["// --- generated by tex_minig.py ---"] + self.subs) + "\n")


def common():
    # minigame titles: re-pack into 6 rows of 26px, keep each title centred where it was
    data, p, im = load("COMMON", "mgtitle")
    im = Image.new("RGBA", im.size, (0, 0, 0, 0))
    lay = Layout("COMMON")
    titles = [  # (layout line pattern, old uv, old x, text)
        (r"title,\s*mgtitle.tm2,\s*xy:212:130", "uv:0:0:217:26", 212, "Agility Test (Button Mash)"),
        (r"title,\s*mgtitle.tm2,\s*xy:217:123", "uv:1:26:201:25", 217, "Quick Thinking (Math)"),
        (r"title,\s*mgtitle.tm2,\s*xy:212:82", "uv:0:51:221:25", 212, "Memory Test (Matching)"),
        (r"title,\s*mgtitle.tm2,\s*xy:250:102", "uv:0:76:147:26", 250, "Reflex Test"),
        (r"minig5,\s*mgtitle.tm2", "uv:1:101:83:26", 273, "Entrance Exam"),
        (r"minig6,\s*mgtitle.tm2", "uv:91:101:134:26", 255, "Spin the Slots"),
    ]
    for k, (pat, olduv, oldx, text) in enumerate(titles):
        spr, size = sprite(text, 26, dict(GOLD, max=21), 256)
        y = k * 26
        im.alpha_composite(spr, (0, y))
        ow = int(olduv.split(":")[3])
        newx = oldx + ow // 2 - spr.width // 2
        i, l = lay.find(pat)
        oldxy = re.search(r"xy:\d+:\d+", l).group(0)
        lay.subs.append(f"{i}\t<SUB>\t{olduv}\tuv:0:{y}:{spr.width}:26")
        lay.subs.append(f"{i}\t<SUB>\t{oldxy}\txy:{newx}:{oldxy.split(':')[2]}")
        print("title", text, spr.width, size)
    save("COMMON", "mgtitle", data, p, im)
    lay.write()

    # "クリア率" -> "Score"
    data, p, im = load("COMMON", "mgfont00")
    put(im, (0, 24, 66, 24), "Score", dict(GOLD_N, max=20))
